#!/usr/bin/env bash
# refresh-cloudflare-ips.sh — regenerate nginx/cloudflare-real-ip.conf from Cloudflare's lists.
#
# The demo sits behind Cloudflare (proxied). nginx must take the visitor's address from
# CF-Connecting-IP ONLY when the TCP peer is a Cloudflare edge; from anyone else the header
# is ignored (ngx_http_realip_module: the header is honoured solely for peers matched by
# set_real_ip_from). The committed nginx/cloudflare-real-ip.conf is a pinned snapshot of the
# published lists; run this to refresh it, review the diff, commit it.
#
#   scripts/demo/refresh-cloudflare-ips.sh            # rewrite the snapshot
#   scripts/demo/refresh-cloudflare-ips.sh --check    # exit 1 if the snapshot is stale
#
# Sources (Cloudflare docs: https://developers.cloudflare.com/fundamentals/concepts/cloudflare-ip-addresses/):
#   https://www.cloudflare.com/ips-v4   https://www.cloudflare.com/ips-v6
# Override with CF_IPS_V4_URL / CF_IPS_V6_URL (file:// works; the tests use it).
# Output path override: CF_REAL_IP_CONF.
# Exit: 0 ok, 1 stale (--check), 2 misuse or a malformed/empty list (nothing is written).

set -euo pipefail

CHECK=0
case "${1:-}" in
    --check) CHECK=1 ;;
    "") ;;
    -h | --help) sed -n '2,16p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
esac

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="${CF_REAL_IP_CONF:-$ROOT/nginx/cloudflare-real-ip.conf}"
V4_URL="${CF_IPS_V4_URL:-https://www.cloudflare.com/ips-v4}"
V6_URL="${CF_IPS_V6_URL:-https://www.cloudflare.com/ips-v6}"

fetch() {
    local out
    out="$(curl -fsS --max-time 30 "$1")" || { echo "cannot fetch $1" >&2; exit 2; }
    out="$(printf '%s\n' "$out" | tr -d '\r' | sed '/^[[:space:]]*$/d')"
    [ -n "$out" ] || { echo "empty list from $1" >&2; exit 2; }
    # Every line must be exactly one CIDR: a stray HTML error page must never become nginx config.
    if printf '%s\n' "$out" | grep -qvE '^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$|^[0-9a-fA-F:]+/[0-9]{1,3}$'; then
        echo "unexpected content from $1 (not a CIDR list)" >&2; exit 2
    fi
    printf '%s\n' "$out"
}

V4="$(fetch "$V4_URL")"
V6="$(fetch "$V6_URL")"

render() {
    cat <<HDR
# Generated by scripts/demo/refresh-cloudflare-ips.sh from Cloudflare's published ranges
# (https://www.cloudflare.com/ips-v4, https://www.cloudflare.com/ips-v6). Do not edit by hand.
#
# Mounted into /etc/nginx/conf.d/ by docker-compose.demo.yml, which nginx includes at http
# level. A request whose TCP peer is one of the ranges below has its client address replaced
# with CF-Connecting-IP; from any other peer the header is ignored. Do not enable
# real_ip_recursive: it would trust the header across further hops.
HDR
    printf '%s\n' "$V4" | sed 's/.*/set_real_ip_from &;/'
    printf '%s\n' "$V6" | sed 's/.*/set_real_ip_from &;/'
    echo "real_ip_header CF-Connecting-IP;"
}

if [ "$CHECK" = 1 ]; then
    render | diff -u "$OUT" - >/dev/null || { echo "$OUT is stale; run scripts/demo/refresh-cloudflare-ips.sh" >&2; exit 1; }
    echo "up to date"
else
    render >"$OUT"
    echo "wrote $OUT"
fi
