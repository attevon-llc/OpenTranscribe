"""styling-ab.sh gives a tree its own `npm ci` when its lockfile differs from the checkout's."""

import os
import stat
import subprocess
from pathlib import Path

LIB = Path(__file__).resolve().parents[3] / "scripts" / "e2e" / "styling-ab-deps.sh"


def _tree(root: Path, name: str, lock: str) -> Path:
    d = root / name / "frontend"
    d.mkdir(parents=True)
    (d / "package-lock.json").write_text(lock)
    return d


def _run(
    tmp_path: Path, tree_lock: str, shared_lock: str
) -> tuple[subprocess.CompletedProcess, Path]:
    stub_dir = tmp_path / "bin"
    stub_dir.mkdir()
    npm = stub_dir / "npm"
    npm.write_text(
        '#!/bin/bash\necho "npm $*" >> "$NPM_STUB_LOG"\nmkdir -p node_modules/own-marker\n'
    )
    npm.chmod(npm.stat().st_mode | stat.S_IXUSR)
    tree = _tree(tmp_path, "after", tree_lock)
    shared = tmp_path / "shared_nm"
    shared.mkdir()
    lock = tmp_path / "checkout-lock.json"
    lock.write_text(shared_lock)
    env = {
        **os.environ,
        "PATH": f"{stub_dir}:{os.environ['PATH']}",
        "NPM_STUB_LOG": str(tmp_path / "npm.log"),
    }
    script = (
        f'. "{LIB}"; ab_provision_node_modules after "{tree}" "{shared}" "{lock}" "{tmp_path}/logs"'
    )
    proc = subprocess.run(
        ["bash", "-c", script], env=env, capture_output=True, text=True, check=False
    )
    return proc, tree


def test_equal_locks_share_node_modules_without_installing(tmp_path):
    proc, tree = _run(tmp_path, '{"a":1}', '{"a":1}')
    assert proc.returncode == 0, proc.stderr
    assert (tree / "node_modules").is_symlink()
    assert not (tmp_path / "npm.log").exists()
    assert "shares" in proc.stdout


def test_differing_locks_run_npm_ci_in_that_tree(tmp_path):
    proc, tree = _run(tmp_path, '{"a":2}', '{"a":1}')
    assert proc.returncode == 0, proc.stderr
    assert not (tree / "node_modules").is_symlink()
    assert (tree / "node_modules" / "own-marker").is_dir()
    assert (tmp_path / "npm.log").read_text().startswith("npm ci")
    assert "differs" in proc.stdout and "after" in proc.stdout
    assert (tmp_path / "logs" / "npm-ci-after.log").exists()
