"""``README.md`` and ``MANIFEST.tsv`` for a generated corpus.

Both live outside the determinism set: they carry a wall-clock stamp, and a timestamp
inside a byte-comparison would make the reproducibility proof unfalsifiable in the wrong
direction — it would always fail. The manifest's ``manifest_sha256`` is the digest of
``SHA256SUMS``, which *is* deterministic, so one column still pins the whole corpus.

Column set matches the established NAS manifests
(``dataset tier files bytes manifest_sha256 license source_url fetched_utc``) plus the two
columns this tier needs: ``seed`` and ``generator_version``.
"""

from __future__ import annotations

import hashlib
import json
import time
from pathlib import Path

MANIFEST_COLUMNS = (
    "dataset",
    "tier",
    "files",
    "bytes",
    "manifest_sha256",
    "license",
    "source_url",
    "fetched_utc",
    "seed",
    "generator_version",
)
LICENSE = "AGPL-3.0-or-later (generated by OpenTranscribe; no third-party text)"
SOURCE = "backend/tests/eval/synthetic/ (OpenTranscribe repo)"


def _tree_size(corpus_dir: Path) -> tuple[int, int]:
    files = [p for p in sorted(corpus_dir.rglob("*")) if p.is_file()]
    return len(files), sum(p.stat().st_size for p in files)


def write_manifest(corpus_dir: Path, config: dict) -> Path:
    """Write ``MANIFEST.tsv`` for the corpus and return its path."""
    corpus_dir = Path(corpus_dir)
    count, size = _tree_size(corpus_dir)
    digest = hashlib.sha256((corpus_dir / "SHA256SUMS").read_bytes()).hexdigest()
    row = {
        "dataset": config["corpus_id"],
        # Tier A: generated by us from our own grammar, so a metric derived from it MAY
        # be published. That is the entire reason this tier exists.
        "tier": "A",
        "files": count,
        "bytes": size,
        "manifest_sha256": digest,
        "license": LICENSE,
        "source_url": SOURCE,
        "fetched_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "seed": config["seed"],
        "generator_version": config["generator_version"],
    }
    path = corpus_dir / "MANIFEST.tsv"
    lines = ["\t".join(MANIFEST_COLUMNS), "\t".join(str(row[c]) for c in MANIFEST_COLUMNS)]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path


def write_readme(corpus_dir: Path, config: dict, stats: dict, metrics: dict | None = None) -> Path:
    """Write the corpus ``README.md`` and return its path."""
    corpus_dir = Path(corpus_dir)
    words = stats["words_per_meeting"]
    regen = (
        "cd backend && python3 -m tests.eval.synthetic generate "
        f"--out <dir> --corpus-id {config['corpus_id']} --seed {config['seed']} "
        f"--meetings {config['meetings']} "
        f"--near-duplicate-rate {config['near_duplicate_rate']}"
    )
    body = [
        f"# {config['corpus_id']} — synthetic meeting corpus (Tier A)",
        "",
        "Generated by OpenTranscribe's own template grammar for issue #403 Stage 1. **No",
        "third-party text, no LLM, and no network access is involved in generation**, so a",
        "metric derived from this corpus is publishable (Tier A) and the corpus itself is",
        "redistributable under the repository's licence.",
        "",
        "Method, design rationale and the reviewer-facing weaknesses:",
        "`.rag-403/synthetic-tier-design.md` in the OpenTranscribe repo.",
        "",
        "## Reproducing this exact corpus",
        "",
        "```bash",
        regen,
        "```",
        "",
        "Then compare: `sha256sum -c SHA256SUMS`. Every file listed there is byte-identical",
        "for a given seed and config. `README.md` and `MANIFEST.tsv` are excluded because",
        "they record a wall-clock generation time.",
        "",
        "## Layout",
        "",
        "| Path | Contents |",
        "|---|---|",
        "| `config.json` | Seed, generator version, and every knob. The reproducibility record. |",
        "| `meetings/part-*.jsonl` | One meeting per line: metadata + speaker-attributed, timestamped turns. |",
        "| `queries.jsonl` | Queries with `query_class`, `surface`, `rule`, `gold_files`, `gold_turns`, exact `answer`. |",
        "| `qrels-files.tsv` | TREC qrels at file granularity (`qid 0 docid rel`). |",
        "| `facts.jsonl` | Provenance: every planted fact, its rule, its file, its turn span. |",
        "| `stats.json` | Corpus statistics (deterministic). |",
        "| `metrics.json` | BM25 characterisation (a measurement, regenerated by `measure`). |",
        "| `SHA256SUMS` | Digest of every file the determinism claim covers. |",
        "",
        "## What was generated",
        "",
        f"- **{stats['meetings']:,} meetings**, {stats['total_words']:,} words, "
        f"{stats['total_turns']:,} turns, {stats['teams']} teams, {stats['series']} series.",
        f"- Words per meeting: median {words['median']:,}, mean {words['mean']:,}, "
        f"p10 {words['p10']:,}, p90 {words['p90']:,}.",
        f"- Speakers per meeting: median {stats['speakers_per_meeting']['median']}, "
        f"range {stats['speakers_per_meeting']['min']}-{stats['speakers_per_meeting']['max']}.",
        f"- Registers: {stats['registers']}.",
        f"- Near-duplicate dial: join probability "
        f"{stats['near_duplicate_join_probability']}, "
        f"{stats['near_duplicate_fraction_in_clusters']:.1%} of meetings in a cluster.",
        f"- Queries: {stats['queries_total']:,} — {stats['queries_by_class']}.",
        "",
        "## Ground truth",
        "",
        "Correct by construction and re-checked by brute force over the written files:",
        "",
        "```bash",
        "cd backend && python3 -m tests.eval.synthetic validate <dir>",
        "```",
        "",
        "Checks V1-V10 re-derive every gold set and every aggregation answer from the text",
        "on disk, ignoring the generator's write log. A disagreement fails the run.",
        "",
    ]
    if metrics:
        overall = metrics.get("overall", {})
        body += [
            "## Measured difficulty (BM25, whole meeting as one document)",
            "",
            f"Overall R@1 {overall.get('R@1')}, MRR {overall.get('MRR')}, "
            f"mean near-duplicate competitors "
            f"{overall.get('near_duplicate_competitors_mean')} "
            f"({overall.get('near_duplicate_competitors_pct_of_pool')}% of pool).",
            "Per class and surface: see `metrics.json`.",
            "",
        ]
    body += [
        "## Caveats a reader must carry",
        "",
        "- **Synthetic queries are not human queries.** Report these results as a scaling",
        "  study beside the human-judged QMSum numbers, never as a replacement.",
        "- Meeting text is template-generated; lexical diversity is far below real speech.",
        "- The generator's own statistics are fitted to QMSum's three domains, measured on",
        "  2026-08-12; the fit is on length, speaker count, turn length, filler rate and",
        "  short-turn fraction, not on semantics.",
        "",
    ]
    path = corpus_dir / "README.md"
    path.write_text("\n".join(body), encoding="utf-8", newline="\n")
    return path


def load_config(corpus_dir: Path) -> dict:
    """Read a corpus's ``config.json``."""
    loaded: dict = json.loads((Path(corpus_dir) / "config.json").read_text(encoding="utf-8"))
    return loaded
