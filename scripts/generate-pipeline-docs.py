#!/usr/bin/env python3
"""Generate or verify the docs-site tables that describe the processing pipeline (#1230).

Usage:
    backend/venv/bin/python scripts/generate-pipeline-docs.py --write   # regenerate
    backend/venv/bin/python scripts/generate-pipeline-docs.py --check   # verify (CI)

Three Markdown partials under ``docs-site/docs/installation/_generated/`` are imported by the
Deployment variants page. Each is computed from the code or script that decides it, so the
page cannot drift from what ships:

- ``images.md``: ``./scripts/docker-build-push.sh list-platforms`` (component, capability,
  platforms) joined with ``./scripts/security-scan.sh list-repos`` (component, repository).
- ``provider-speakers.md``: ``ASR_PROVIDER_CATALOG`` read through
  ``ASRProviderFactory.get_model_capabilities`` (the same call the pipeline plan uses).
- ``validity-matrix.md``: ``resolve_pipeline_plan`` run over fixed inputs, one cell per
  transcription kind x speaker-detection choice, for the full and the lite image. The cloud
  rows take their capabilities from the catalog, never from this file.

Like ``generate-openapi.py`` it imports ``app``, so it needs the backend venv (or the CI
backend job), runs from ``backend/`` and never reads the operator's ``.env``.
"""

from __future__ import annotations

import argparse
import difflib
import os
import subprocess  # nosec B404 - runs two of this repo's own scripts with fixed argv
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BACKEND_DIR = REPO_ROOT / 'backend'
OUT_DIR = REPO_ROOT / 'docs-site' / 'docs' / 'installation' / '_generated'
HEADER = (
    '{{/* GENERATED by scripts/generate-pipeline-docs.py from {source}. Do not edit: run\n'
    '    backend/venv/bin/python scripts/generate-pipeline-docs.py --write */}}\n\n'
)


def _prepare_environment() -> None:
    """Make ``app`` importable without a stack and without the operator's ``.env``."""
    if 'app' in sys.modules:  # imported by a test session that already configured this
        return
    tmp = tempfile.gettempdir()
    for key in ('TEMP_DIR', 'DATA_DIR', 'MODELS_DIR'):
        os.environ.setdefault(key, tmp)
    os.environ.setdefault('TESTING', 'True')
    os.chdir(BACKEND_DIR)
    if str(BACKEND_DIR) not in sys.path:
        sys.path.insert(0, str(BACKEND_DIR))


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    lines += ['| ' + ' | '.join(row) + ' |' for row in rows]
    return '\n'.join(lines) + '\n'


def _script_rows(*argv: str) -> list[list[str]]:
    out = subprocess.run(  # nosec B603 - fixed argv, repo-local script
        list(argv), cwd=REPO_ROOT, check=True, capture_output=True, text=True
    ).stdout
    return [line.split('\t') for line in out.splitlines() if line.strip()]


# --- images ---------------------------------------------------------------------------------

_IMAGE_ROLE = {
    'backend': 'Backend, Full (GPU) and CPU-only',
    'blackwell': 'Backend, Full (GPU) on Blackwell arm64 (DGX Spark); built on request only',
    'lite': 'Backend, Lite (cloud-only)',
    'frontend': 'Web app (every variant)',
    'docs': 'This documentation site',
}


def _tags(capability: str, platforms: list[str]) -> str:
    """The tag grammar ``docker-build-push.sh`` publishes for a capability (issue #680)."""
    if capability == 'multiarch':
        return '`vX.Y.Z`, `latest`'
    arches = [p.removeprefix('linux/') for p in platforms]
    legs = ', '.join(f'`vX.Y.Z-{capability}-{a}`' for a in arches)
    if capability == 'blackwell':
        return f'`blackwell`, {legs}'
    return f'`vX.Y.Z`, `latest` (index over {legs})'


def render_images() -> str:
    repos = dict(_script_rows('./scripts/security-scan.sh', 'list-repos'))
    rows = []
    for component, capability, platforms in _script_rows(
        './scripts/docker-build-push.sh', 'list-platforms'
    ):
        plats = [p for p in platforms.split(',') if p]
        rows.append(
            [
                f'`{repos[component]}`',
                _IMAGE_ROLE.get(component, component),
                f'`{capability}`',
                ', '.join(f'`{p}`' for p in plats),
                _tags(capability, plats),
            ]
        )
    header = ['Image', 'Used for', 'Capability', 'Architectures', 'Tags']
    source = 'docker-build-push.sh list-platforms and security-scan.sh list-repos'
    return HEADER.format(source=source) + _table(header, rows)


# --- providers ------------------------------------------------------------------------------

_TIMING_TEXT = {'word': 'Word', 'segment': 'Segment', 'none': 'None (no timestamps)'}
_TIMING_LABEL = {'word': 'word timing', 'segment': 'segment timing', 'none': 'no timing'}


def _hints(hints) -> str:
    return ', '.join(h for h in ('min', 'max', 'num') if h in set(hints)) or 'none'


def render_provider_speakers() -> str:
    _prepare_environment()
    from app.services.asr.factory import ASR_PROVIDER_CATALOG, ASRProviderFactory
    from app.services.pipeline_plan import ALL_HINTS

    rows = []
    for provider, entry in ASR_PROVIDER_CATALOG.items():
        if provider == 'local':
            continue
        for model in entry.get('models', []):
            caps = ASRProviderFactory.get_model_capabilities(provider, model['id'])
            rows.append(
                [
                    entry['display_name'],
                    f'{model.get("display_name", model["id"])} (`{model["id"]}`)',
                    'Yes' if caps['supports_diarization'] else 'No (text only)',
                    _TIMING_TEXT[caps['timestamp_granularity']],
                    _hints(caps['speaker_count_hints']),
                    str(model.get('status') or entry.get('status') or ''),
                ]
            )
    rows.append(
        [
            'pyannote.ai (speaker detection only)',
            'account default',
            'Yes (speakers only, no text)',
            'n/a (turns are merged onto your transcript)',
            _hints(ALL_HINTS),
            '',
        ]
    )
    header = [
        'Provider',
        'Model',
        'Returns speakers',
        'Timing',
        'Speaker-count hints sent',
        'Status',
    ]
    source = 'ASR_PROVIDER_CATALOG via ASRProviderFactory.get_model_capabilities'
    return HEADER.format(source=source) + _table(header, rows)


# --- validity matrix ------------------------------------------------------------------------

#: One example per kind of cloud model. Capabilities are read from the catalog at run time;
#: ``_matrix_rows`` refuses an example whose catalog entry no longer matches its row label.
CLOUD_EXAMPLES: list[tuple[str, str, bool, str]] = [
    ('assemblyai', 'universal', True, 'word'),
    ('openai', 'gpt-4o-transcribe-diarize', True, 'segment'),
    ('openai', 'whisper-1', False, 'segment'),
    ('openai', 'gpt-4o-transcribe', False, 'none'),
]
#: The saved provider used only for speakers in the "Another provider" column.
DIARIZER_EXAMPLE = ('deepgram', 'nova-3')

COLUMNS: list[tuple[str, str]] = [
    ('provider', 'Automatic'),
    ('local', 'This server'),
    ('pyannote', 'pyannote.ai'),
    ('asr_config', 'Another provider (speakers only)'),
    ('off', 'Off'),
]

_EXECUTION_TEXT = {
    'inline_asr': 'Speakers from the transcription vendor',
    'inline_local': 'This server, during transcription',
    'post_stage_local': 'This server, after transcription',
    'parallel_cloud': 'By {who}, alongside transcription',
    'post_stage_cloud': 'By {who}, after transcription',
}
_WHO = {'pyannote_ai': 'pyannote.ai', 'asr_config': 'the other provider'}
#: Warnings worth a word in a cell. Info codes and ``speaker_hints_ignored`` are left to
#: the page's prose (the hints rule depends on the admin's engine, not on this table).
_WARNING_TEXT = {
    'diarizer_double_billing': 'extra billing',
    'segment_timing_only': 'segment merge',
}


def _cell(plan) -> str:
    blocking = plan.blocking()
    if blocking:
        return 'Refused: ' + ', '.join(f'`{i.code}`' for i in blocking)
    d = plan.diarization
    if d.engine == 'off':
        return 'No speakers'
    if d.execution == 'none':
        return 'No speakers'
    text = _EXECUTION_TEXT[d.execution].format(who=_WHO.get(d.engine, d.provider))
    notes = [_WARNING_TEXT[i.code] for i in plan.issues if i.code in _WARNING_TEXT]
    if notes:
        text += ' (' + ', '.join(notes) + ')'
    return text


def _matrix_rows(mode: str) -> list[list[str]]:
    from app.services.asr.factory import ASR_PROVIDER_CATALOG, ASRProviderFactory
    from app.services.pipeline_plan import DiarizerConfigInfo, PlanInputs, resolve_pipeline_plan

    d_caps = ASRProviderFactory.get_model_capabilities(*DIARIZER_EXAMPLE)
    diarizer = DiarizerConfigInfo(
        provider=DIARIZER_EXAMPLE[0],
        model=DIARIZER_EXAMPLE[1],
        uuid='example',
        returns_speakers=bool(d_caps['supports_diarization']),
        speaker_hints=frozenset(d_caps['speaker_count_hints']),
    )

    kinds: list[tuple[str, dict]] = [
        (
            "This server, the deployment's Whisper model",
            {'asr_provider': 'local', 'asr_model': 'large-v3-turbo', 'asr_timing': 'word'},
        ),
        (
            'This server, per-file `tiny`/`base` model (CPU worker)',
            {
                'asr_provider': 'local',
                'asr_model': 'large-v3-turbo',
                'asr_timing': 'word',
                'cpu_whisper_model': 'base',
            },
        ),
    ]
    for provider, model, speakers, timing in CLOUD_EXAMPLES:
        caps = ASRProviderFactory.get_model_capabilities(provider, model)
        actual = (bool(caps['supports_diarization']), caps['timestamp_granularity'])
        if actual != (speakers, timing):
            raise SystemExit(
                f'error: example {provider}/{model} is now {actual} in the catalog, not '
                f'{(speakers, timing)}; pick another example in CLOUD_EXAMPLES'
            )
        name = ASR_PROVIDER_CATALOG[provider]['display_name']
        label = (
            f'Cloud, {"returns speakers" if speakers else "text only"}, '
            f'{_TIMING_LABEL[timing]} (e.g. {name} `{model}`)'
        )
        kinds.append(
            (
                label,
                {
                    'asr_provider': provider,
                    'asr_model': model,
                    'asr_timing': timing,
                    'asr_returns_speakers': speakers,
                    'asr_speaker_hints': frozenset(caps['speaker_count_hints']),
                },
            )
        )

    rows = []
    for label, fields in kinds:
        cells = [label]
        for source, _title in COLUMNS:
            inputs = PlanInputs(
                deployment_mode=mode,
                asr_provider=fields['asr_provider'],
                asr_model=fields['asr_model'],
                asr_config_uuid=None,
                asr_returns_speakers=fields.get('asr_returns_speakers', True),
                asr_speaker_hints=fields.get('asr_speaker_hints', frozenset()),
                asr_timing=fields['asr_timing'],
                diarization_source=source,
                has_pyannote_key=True,
                diarization_config=diarizer if source == 'asr_config' else None,
                cpu_whisper_model=fields.get('cpu_whisper_model'),
            )
            cells.append(_cell(resolve_pipeline_plan(inputs)))
        rows.append(cells)
    return rows


def render_validity_matrix() -> str:
    _prepare_environment()
    header = ['Transcription \\ Speaker detection'] + [title for _s, title in COLUMNS]
    parts = [HEADER.format(source='resolve_pipeline_plan in backend/app/services/pipeline_plan.py')]
    for mode, title in (('full', 'Full image (GPU or CPU-only)'), ('lite', 'Lite image')):
        parts.append(f'**{title}**\n\n')
        parts.append(_table(header, _matrix_rows(mode)))
        parts.append('\n')
    return ''.join(parts).rstrip('\n') + '\n'


GENERATORS: dict[str, Callable[[], str]] = {
    'images.md': render_images,
    'provider-speakers.md': render_provider_speakers,
    'validity-matrix.md': render_validity_matrix,
}


def drift(out_dir: Path = OUT_DIR, generated: dict[str, str] | None = None) -> list[str]:
    """Names (with a short diff) of partials whose committed text differs from the code's."""
    generated = generated if generated is not None else {n: g() for n, g in GENERATORS.items()}
    problems = []
    for name, text in generated.items():
        path = out_dir / name
        if not path.is_file():
            problems.append(f'{name} is missing from {out_dir}')
            continue
        current = path.read_text(encoding='utf-8')
        if current != text:
            diff = ''.join(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    text.splitlines(keepends=True),
                    f'committed/{name}',
                    f'generated/{name}',
                )
            )
            problems.append(f'{name} is stale:\n{diff}')
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true', help='regenerate the partials')
    mode.add_argument('--check', action='store_true', help='fail if a partial is stale')
    args = parser.parse_args()

    if args.write:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for name, generate in GENERATORS.items():
            (OUT_DIR / name).write_text(generate(), encoding='utf-8')
            print(f'wrote {OUT_DIR / name}')
        return 0
    problems = drift()
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print(
            'error: regenerate with backend/venv/bin/python scripts/generate-pipeline-docs.py '
            '--write and commit the result',
            file=sys.stderr,
        )
        return 1
    print(f'pipeline docs tables are current ({len(GENERATORS)} files)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
