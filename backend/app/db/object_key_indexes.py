"""One owning row per stored object key, enforced by partial unique indexes on ``media_file``.

Deleting an object removes every version of its key, so a key two rows name loses both rows'
history when either is purged. The indexes make that state unrepresentable. Shared by the v456
revision, the startup retry, the admin status endpoint and the remediation script, so the
definitions cannot drift apart.

Building an index NEVER blocks startup. ``ensure_indexes`` checks for duplicates first and, for a
column that has any, skips that index, logs an ERROR naming the count, and reports it through
:func:`status`; the next start (or the remediation script) builds it once the rows are clean.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass

import sqlalchemy as sa
from sqlalchemy import text
from sqlalchemy.engine import Connection
from sqlalchemy.exc import DBAPIError

logger = logging.getLogger(__name__)

TABLE = "media_file"  # pg_indexes lookup only


# A private minimal Table (not the ORM model): migrations must not track model drift.
_MEDIA_FILE = sa.Table(
    "media_file",
    sa.MetaData(),
    sa.Column("id", sa.Integer),
    sa.Column("storage_path", sa.String),
    sa.Column("thumbnail_path", sa.String),
    sa.Column("playback_path", sa.String),
)


@dataclass(frozen=True)
class KeyIndex:
    """A unique index over one object-key column of ``media_file``."""

    name: str
    column: str

    @property
    def col(self) -> sa.ColumnElement:
        return _MEDIA_FILE.c[self.column]

    @property
    def predicate(self) -> sa.ColumnElement[bool]:
        # '' is the placeholder an upload row carries until its object exists.
        return sa.and_(self.col.is_not(None), self.col != "")

    def index(self) -> sa.Index:
        """The ``sa.Index`` (``CREATE UNIQUE INDEX ... WHERE``) for this column."""
        return sa.Index(
            self.name,
            self.col,
            unique=True,
            postgresql_where=self.predicate,
        )


STORAGE_PATH = KeyIndex("uq_media_file_storage_path", "storage_path")
THUMBNAIL_PATH = KeyIndex("uq_media_file_thumbnail_path", "thumbnail_path")
PLAYBACK_PATH = KeyIndex("uq_media_file_playback_path", "playback_path")

#: Build order. The detection arm keys on the LAST one, which every completed run has built;
#: ``storage_path`` can legitimately be absent (see the module docstring).
INDEXES = (STORAGE_PATH, THUMBNAIL_PATH, PLAYBACK_PATH)

#: Columns whose duplicates the migration resolves on its own (a thumbnail or playback copy is
#: regenerable). ``storage_path`` is the original upload and is not.
REGENERABLE = (THUMBNAIL_PATH, PLAYBACK_PATH)


def duplicate_groups(conn: Connection, index: KeyIndex) -> list[tuple[str, list[int]]]:
    """Every key held by more than one row, with the row ids holding it."""
    stmt = (
        sa.select(index.col, sa.func.array_agg(_MEDIA_FILE.c.id))
        .where(index.predicate)
        .group_by(index.col)
        .having(sa.func.count() > 1)
    )
    return [(str(r[0]), sorted(int(i) for i in r[1])) for r in conn.execute(stmt)]


def clear_regenerable_duplicates(conn: Connection) -> dict[str, int]:
    """Keep the lowest-id row per shared thumbnail/playback key; NULL the rest.

    Returns:
        ``{column: rows_cleared}``. The cleared rows are regenerated by a batch task.
    """
    cleared: dict[str, int] = {}
    for index in REGENERABLE:
        ranked = (
            sa.select(
                _MEDIA_FILE.c.id,
                sa.func.row_number()
                .over(partition_by=index.col, order_by=_MEDIA_FILE.c.id)
                .label("rn"),
            )
            .where(index.predicate)
            .subquery()
        )
        losers = sa.select(ranked.c.id).where(ranked.c.rn > 1)
        result = conn.execute(
            sa.update(_MEDIA_FILE).where(_MEDIA_FILE.c.id.in_(losers)).values({index.column: None})
        )
        cleared[index.column] = int(getattr(result, "rowcount", 0) or 0)
    return cleared


def existing_indexes(conn: Connection) -> set[str]:
    """Names of the key indexes already present."""
    rows = conn.execute(
        text("SELECT indexname FROM pg_indexes WHERE tablename = :t AND indexname = ANY(:n)"),
        {"t": TABLE, "n": [i.name for i in INDEXES]},
    )
    return {str(r[0]) for r in rows}


def ensure_indexes(conn: Connection) -> dict[str, str]:
    """Build every index whose column is free of duplicates; never raise on a build problem.

    Returns:
        ``{index_name: "exists" | "built" | "skipped_duplicates" | "failed"}``.
    """
    outcome: dict[str, str] = {}
    present = existing_indexes(conn)
    for index in INDEXES:
        if index.name in present:
            outcome[index.name] = "exists"
            continue
        dupes = duplicate_groups(conn, index)
        if dupes:
            outcome[index.name] = "skipped_duplicates"
            logger.error(
                "Not building %s: %d %s value(s) are shared by %d media_file rows. Startup "
                "continues. Resolve with 'python -m app.scripts.split_shared_storage_paths "
                "--apply'; the index is built on the next start. Status: "
                "GET /api/admin/data-integrity/storage/keys",
                index.name,
                len(dupes),
                index.column,
                sum(len(ids) for _, ids in dupes),
            )
            continue
        try:
            with conn.begin_nested():
                index.index().create(conn, checkfirst=True)
            outcome[index.name] = "built"
        except DBAPIError:
            outcome[index.name] = "failed"
            logger.error("Could not build %s; startup continues", index.name, exc_info=True)
    return outcome


def status(conn: Connection) -> dict[str, object]:
    """Counts only: which indexes exist and how many keys/rows still violate each."""
    present = existing_indexes(conn)
    report: dict[str, object] = {}
    healthy = True
    for index in INDEXES:
        groups = duplicate_groups(conn, index)
        entry = {
            "index_present": index.name in present,
            "duplicate_keys": len(groups),
            "duplicate_rows": sum(len(ids) for _, ids in groups),
        }
        healthy = healthy and entry["index_present"] is True
        report[index.column] = entry
    report["healthy"] = healthy
    return report
